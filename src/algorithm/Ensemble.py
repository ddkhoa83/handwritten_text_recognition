
import numpy as np
from sklearn.model_selection import KFold


class ManualStackingEnsemble:
    """
    A manually implemented stacking ensemble classifier.

    The ensemble combines multiple base classifiers with a meta-learner.
    Out-of-fold (OOF) class probabilities generated by K-fold cross-validation
    are used to train the meta-learner, reducing information leakage between
    base-model training and meta-model training.

    Parameters
    ----------
    base_models : list
        A list of initialized base classifiers. Each classifier must implement
        the fit() and predict_proba() methods.
    meta_model : object
        The meta-learner used to combine the predictions of the base models.
        It must implement the fit() and predict() methods.
    cv_folds : int, default=5
        The number of folds used for generating out-of-fold predictions.
        Must be at least 2 and no greater than the number of samples.

    Attributes
    ----------
    base_models : list
        The base classifiers used by the ensemble. After fitting, each model
        is trained on the complete training dataset.
    meta_model : object
        The fitted meta-learner trained on the OOF prediction features.
    cv_folds : int
        The number of cross-validation folds.
    classes_ : NDArray
        The unique class labels observed in the training data.
    """

    def __init__(self, base_models, meta_model, cv_folds=5):
        """
        Initialize the stacking ensemble classifier.

        Parameters
        ----------
        base_models : list
            A list of initialized base classifiers.
        meta_model : object
            The meta-learner that combines the base-model predictions.
        cv_folds : int, default=5
            The number of folds used for cross-validation.
        """
        self.base_models = base_models
        self.meta_model = meta_model
        self.cv_folds = cv_folds

    def fit(self, X, y):
        """
        Fit the stacking ensemble using the training data.

        Generate out-of-fold class probabilities from each base classifier,
        use them as input features to train the meta-learner, and then
        refit each base classifier on the complete training dataset.

        Parameters
        ----------
        X : NDArray[np.float64]
            Training features of shape (n_samples, n_features).
        y : NDArray[np.int64]
            Training class labels of shape (n_samples,).

        Returns
        -------
        ManualStackingEnsemble
            The fitted stacking ensemble.
        """
        # Initialize shuffled K-fold cross-validation.
        kf = KFold(
            n_splits=self.cv_folds,
            shuffle=True,
            random_state=42
        )

        n_samples = X.shape[0]
        self.classes_ = np.unique(y)
        n_classes = len(self.classes_)

        # Allocate a feature matrix for the out-of-fold predictions.
        # Each base model contributes one probability column per class.
        num_base = len(self.base_models)
        oof_features = np.zeros(
            (n_samples, num_base * n_classes)
        )

        # Generate out-of-fold predictions for each base model.
        for i, model in enumerate(self.base_models):
            for train_idx, val_idx in kf.split(X):
                # Split the data into training and validation subsets.
                X_train_fold = X[train_idx]
                X_val_fold = X[val_idx]
                y_train_fold = y[train_idx]

                # Train the base model on the current training fold.
                model.fit(X_train_fold, y_train_fold)

                # Predict class probabilities for the validation fold.
                preds = model.predict_proba(X_val_fold)

                # Store the predictions in the corresponding feature columns.
                start_col = i * n_classes
                end_col = (i + 1) * n_classes
                oof_features[val_idx, start_col:end_col] = preds

            # Refit the base model on the complete training dataset.
            model.fit(X, y)

        # Train the meta-learner using the OOF prediction features.
        self.meta_model.fit(oof_features, y)

        return self

    def predict(self, X):
        """
        Predict class labels for input samples.

        Obtain class probabilities from all fitted base models, concatenate
        them into a meta-feature matrix, and pass that matrix to the
        meta-learner to obtain the final predictions.

        Parameters
        ----------
        X : NDArray[np.float64]
            Input features of shape (n_samples, n_features).
            The features must use the same preprocessing as the training data.

        Returns
        -------
        NDArray
            Predicted class labels of shape (n_samples,).
        """
        # Collect class probabilities from all base models.
        test_features = []

        for model in self.base_models:
            preds = model.predict_proba(X)
            test_features.append(preds)

        # Concatenate the probability matrices into a single meta-feature matrix.
        X_test_meta = np.hstack(test_features)

        # Generate the final predictions using the meta-learner.
        return self.meta_model.predict(X_test_meta)

    def evaluate(self, X_test, y_test):
        """
        Evaluate the classification accuracy of the ensemble.

        Compare the predicted class labels with the true labels and calculate
        the proportion of correctly classified samples.

        Parameters
        ----------
        X_test : NDArray[np.float64]
            Test features of shape (n_samples, n_features).
        y_test : NDArray[np.int64]
            True class labels of shape (n_samples,).

        Returns
        -------
        float
            Classification accuracy between 0.0 and 1.0.
        """
        # Predict the labels of the test samples.
        y_pred = self.predict(X_test)

        # Calculate the proportion of correct predictions.
        return np.mean(y_pred == y_test)
